#!/usr/bin/env python3
"""Collects every piece of player-facing text the pack itself writes into one file to read through and rename:
our mods' lang files (item and block names, screens, tooltips, status and error lines, EMI pages, Ponder scenes),
text written straight into the Java code (chat messages, boss bars, titles, command replies, screen text),
the quest book, and KubeJS chat messages.

    python tools/text/dump_text.py        writes docs/ingame-text.txt

Lang lines: change the text after " = " in the mod's lang file (mods/<mod>/src/main/resources/assets/<mod>/lang/
en_us.json). Tiered Foundry's lang file is generated by tools/foundry/gen.py, so change it there. Lines marked
[code] are written in the Java file and line shown. Quest lines come from tools/questgen/book.json.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MODS = ['emp_engines', 'expresearch', 'researchenchanting', 'silentraids', 'tieredfoundry', 'weatheredmaps']
NAMES = {'emp_engines': 'Create: Empyrean Engines', 'expresearch': 'EXP Research',
         'researchenchanting': 'Does Enchanting Overhaul (researchenchanting)', 'silentraids': 'Silent Apotheosis Raids',
         'tieredfoundry': 'Tiered Foundry', 'weatheredmaps': 'Weathered Maps'}

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
# lines whose strings are never shown to players
SKIP_LINE = re.compile(r'^\s*(//|\*|/\*)|LOG(GER)?\.|\blog\.|\.comment\(|translatable\(|@\w+\(|ResourceLocation|\.id\(|'
                       r'withDefaultNamespace|fromNamespaceAndPath|getString\("|put\w*\("|get\w*\("|contains\("|'
                       r'register\w*\("|new Type<|Codec|fieldOf|optionalFieldOf|\.is\("|define\w*\(|push\("')
SHOWN_HINT = re.compile(r'literal\(|drawString|Text\.|problem|status|setName|sendSystemMessage|sendSuccess|'
                        r'sendFailure|displayClientMessage|showText|title\(|text\(|NAMES|TIERS|"\s*\+|\+\s*"|return "|'
                        r'= "|\? "|: "')


def player_text(s):
    if len(s) < 3 or not re.search('[A-Za-z]', s):
        return False
    if re.fullmatch(r'[a-z0-9_.:/#%-]+', s):          # ids, paths, keys
        return False
    if re.fullmatch(r'[%.0-9a-zA-Z]*%[^ ]*', s):       # bare format strings
        return False
    return ' ' in s or s[0].isupper()


def lang_section(mod, out):
    path = os.path.join(ROOT, 'mods', mod, 'src', 'main', 'resources', 'assets', mod, 'lang', 'en_us.json')
    if not os.path.exists(path):
        return
    lang = json.load(open(path, encoding='utf-8'))
    groups = {}
    for k, v in lang.items():
        part = k.split('.')[0]
        if '.ponder.' in k:
            part = 'ponder'
        groups.setdefault(part, []).append((k, v))
    for part in sorted(groups):
        out.append(f'  -- {part} --')
        for k, v in groups[part]:
            out.append(f'  {k} = {v}')
        out.append('')


def code_section(mod, out):
    base = os.path.join(ROOT, 'mods', mod, 'src', 'main', 'java')
    found = []
    for dirpath, _, files in os.walk(base):
        for f in sorted(files):
            if not f.endswith('.java'):
                continue
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, os.path.join(ROOT, 'mods', mod, 'src', 'main', 'java'))
            in_block_comment = False
            for n, line in enumerate(open(p, encoding='utf-8'), 1):
                stripped = line.strip()
                if in_block_comment:
                    if '*/' in stripped:
                        in_block_comment = False
                    continue
                if stripped.startswith('/*'):
                    in_block_comment = '*/' not in stripped
                    continue
                if SKIP_LINE.search(line) or not SHOWN_HINT.search(line):
                    continue
                code = line.split('//')[0] if '"' not in line.split('//')[-1] else line
                texts = [t for t in STRING.findall(code) if player_text(t)]
                if texts:
                    found.append(f'  [code] {os.path.basename(rel)}:{n}  ' + '  |  '.join(texts))
    if found:
        out.append('  -- text in the code --')
        out.extend(found)
        out.append('')


def quests(out):
    book = json.load(open(os.path.join(ROOT, 'tools', 'questgen', 'book.json'), encoding='utf-8'))
    out.append('=' * 100)
    out.append('QUEST BOOK  (tools/questgen/book.json, then python tools/questgen/build_quests.py)')
    out.append('=' * 100)
    out.append(f'Book title: {book.get("title", "")}')
    for g in book.get('groups', []):
        out.append(f'Group: {g.get("title", g) if isinstance(g, dict) else g}')
    out.append('')
    for ch in book['chapters']:
        out.append(f'## Chapter: {ch.get("title", "")}' + (f'  -  {ch["subtitle"]}' if ch.get('subtitle') else ''))
        for q in ch.get('quests', []):
            out.append(f'  * {q.get("title", "")}' + (f'  -  {q["subtitle"]}' if q.get('subtitle') else '') + f'   [{q.get("key", "")}]')
            for d in q.get('description', []) or []:
                if d:
                    out.append(f'      {d}')
        out.append('')


def kubejs(out):
    base = os.path.join(ROOT, 'pack', 'kubejs')
    lines = []
    for dirpath, _, files in os.walk(base):
        for f in sorted(files):
            if not f.endswith('.js'):
                continue
            p = os.path.join(dirpath, f)
            for n, line in enumerate(open(p, encoding='utf-8'), 1):
                if 'Text.' not in line and 'tell(' not in line:
                    continue
                texts = re.findall(r'[`\'"]([^`\'"]*[A-Za-z ][^`\'"]*)[`\'"]', line)
                texts = [t for t in texts if ' ' in t]
                if texts:
                    lines.append(f'  [kubejs] {os.path.relpath(p, base)}:{n}  ' + '  |  '.join(texts))
    if lines:
        out.append('=' * 100)
        out.append('KUBEJS CHAT MESSAGES  (pack/kubejs)')
        out.append('=' * 100)
        out.extend(lines)
        out.append('')


def main():
    out = ['All player-facing text the pack writes itself. Generated by tools/text/dump_text.py; edit the sources, not this file.',
           'Lang lines: key = text. [code] lines: file:line, then the text (several strings on one line are joined with |).',
           'Text inside other mods (Create, Silent Gear, Apotheosis...) is not included.', '']
    for mod in MODS:
        out.append('=' * 100)
        out.append(f'{NAMES[mod]}  (mods/{mod})')
        out.append('=' * 100)
        lang_section(mod, out)
        code_section(mod, out)
    quests(out)
    kubejs(out)
    path = os.path.join(ROOT, 'docs', 'ingame-text.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {path}: {len(out)} lines')


if __name__ == '__main__':
    main()
